export function generateMockCandles(basePrice: number = 81000): ChartDataDto {
  const candles = [];
  const indicators: IndicatorsDto[] = [];
  let cur = basePrice;
  const now = Math.floor(Date.now() / 1000);

  for (let i = 60; i >= 0; i--) {
    const time = now - i * 3600;
    const delta = (Math.random() - 0.48) * (cur * 0.015);
    const open = cur;
    const close = cur + delta;
    const high = Math.max(open, close) + Math.random() * (cur * 0.008);
    const low = Math.min(open, close) - Math.random() * (cur * 0.008);
    const volume = Math.floor(100 + Math.random() * 800);
    cur = close;

    candles.push({
      time,
      open: parseFloat(open.toFixed(2)),
      high: parseFloat(high.toFixed(2)),
      low: parseFloat(low.toFixed(2)),
      close: parseFloat(close.toFixed(2)),
      volume,
      is_closed: i > 0,
    });

    indicators.push({
      sma20: parseFloat((cur * (1 + (Math.sin(i / 5) * 0.01))).toFixed(2)),
      sma50: parseFloat((cur * (1 - (Math.cos(i / 10) * 0.015))).toFixed(2)),
      ema12: null,
      ema26: null,
      rsi14: parseFloat((50 + Math.sin(i / 3) * 20).toFixed(1)),
      macd: null,
      macd_signal: null,
      macd_hist: null,
      atr14: null,
      bb_upper: null,
      bb_middle: null,
      bb_lower: null,
    });
  }

  return {
    asset_key: "BINANCE:BTCUSDT",
    symbol: "BTCUSDT",
    venue: "BINANCE",
    timeframe: "1h",
    candles,
    indicators,
    status: "Synchronized",
    error_message: null,
    received_at: new Date().toISOString(),
  };
}

